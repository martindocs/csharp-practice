using DrawingRegister.Data.Context;
using DrawingRegister.Data.Entities;
using Microsoft.AspNetCore.Builder;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.Extensions.DependencyInjection;
using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;
using Type = DrawingRegister.Data.Entities.Type;
using Status = DrawingRegister.Data.Entities.Status;

namespace DrawingRegister.Data.Seeding
{
    public static class SeedData
    {
        public static void PopulateDb(IApplicationBuilder app)
        {
            using var serviceScope = app.ApplicationServices.CreateScope();
            AddInitialData(serviceScope.ServiceProvider.GetService<AppDbContext>()!);
        }

        private static void AddInitialData(AppDbContext appDbContext)
        {
            if (appDbContext.Drawings.Any()) return;


            var projects = new List<Project>()
            {
                new Project
                {
                    Name = "Sling Drawings",
                    Description = "Project about sling patterns and drawings."
                },
                new Project
                {
                    Name = "Mechanical Parts",
                    Description = "Project about mechanical drawings."
                },
                new Project
                {
                    Name = "Literature",
                    Description = "Project about all product literature."
                },
                new Project
                {
                    Name = "Others",
                    Description = "Project for all other things."
                },
            };
            
            appDbContext.Projects.AddRange(projects);
           
            /*
                the number inside the brackets of new Random(...) is only the seed (the starting point for the math formula). It does not restrict how large or small the generated numbers can be.
               
                Random rand = new Random(42); // 42 is just the starting see
            
                Why Use a Seeded Random?

                • Predictable Results: Every single time you run your application, the sequence of numbers generated by this specific instance will be exactly the same.
                • Perfect for Debugging: If your code has a bug that only appears when a specific "random" sequence occurs, using a fixed seed lets you reproduce the exact same scenario over and over until you fix it.
                • Procedural Generation: Games often use seeded randoms to generate the exact same worlds or maps for players who share the same seed code (like Minecraft or Terraria).

                 Random rand = new Random(); // "random" number every time app starts

                When you leave the brackets empty, C# automatically looks at the computer's internal clock and grabs the current time down to the exact millisecond.
                Because time is constantly moving forward, the starting number (the seed) is guaranteed to be different every single time you start the program. That is the only reason it feels truly random!
             */
            var rand = new Random(42);
            var drawings = new List<Drawing>();
            var tagList = new List<string> { "sling", "hoist", "lift", "accessories", "part" };
            var tags = new List<Tag>();

            foreach (var tag in tagList)
            {
                tags.Add(new Tag
                {
                    Name = tag
                });
            }


            for (var i = 1; i <= 150; i++)
            {                
                var shuffletags = tags.OrderBy(_ => rand.Next()).ToList();
                var status = (Status)rand.Next(Enum.GetValues(typeof(Status)).Length);

                drawings.Add(new Drawing
                {
                    DocumentNumber = i,
                    Name = $"Drawing_{i}",
                    Path = "",
                    /*
                        GetValues: actual enum values, example (One, Two, Three). You can assign one straight to a Status property (after a cast, since it comes back as a general Array).

                        GetNames: plain strings, example ("One", "Two", "Three") . To turn one into an enum you’d have to parse it with Enum.Parse or Enum.TryParse, which is an extra step you don’t need.                     
                       */

                    DrawingType = (Type)rand.Next(Enum.GetValues(typeof(Type)).Length), // need casting as rand.Next return int and we need enum type
                    DrawingStatus = status,
                    //  year, month, day
                    ReleaseDate = status == Status.Released ? new DateTime(2020, 10, 25).AddDays(rand.Next(100)) : null,
                    Project = projects[rand.Next(projects.Count)],                   
                    Tags = shuffletags.Take(rand.Next(1, shuffletags.Count)).ToList(),
                });

                
            }

            appDbContext.Drawings.AddRange(drawings);

            
            /*
                Everything you’ve added is only tracked in memory. At the end, EF looks at all of it, works out the insert order from the relationships (projects and tags first, then drawings, then revisions and the join rows) and sends it to the database as a single transaction. If anything fails, nothing is written, so you never end up with half a dataset.

                You’d only save early if your code needed a database-generated Id before continuing.
             
             */
            appDbContext.SaveChanges();
        }

        
    }
}
